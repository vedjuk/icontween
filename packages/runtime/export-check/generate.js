/**
 * Builds the cross-browser export check (decision 018): every starter in every export
 * format, plus a page that checks them in whichever browser opens it.
 *
 *   out/svg/      SVG + SMIL files       out/html/   HTML + runtime pages
 *   out/json/     JSON data              out/react/  a fresh Vite + React app, built
 *   out/index.html, check.js, check.css  the check page (copied from page/)
 *
 * Usage: pnpm export-check (generates, builds the React app, then serves on :5180).
 * The React app is installed once from the pnpm store (no workspace links), so it builds
 * the way a developer's own app would.
 */
import { execFileSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';
import { runnerImport } from 'vite';
import { bundleRuntime } from '../scripts/bundle.js';

const here = fileURLToPath(new URL('.', import.meta.url));
const out = join(here, 'out');
const reactApp = join(out, 'react-app');

// The starters are built with core's prepare pipeline, which needs a DOMParser.
globalThis.DOMParser = new JSDOM('').window.DOMParser;

const load = async (path) =>
  (await runnerImport(join(here, path), { configFile: false, logLevel: 'silent' })).module;
const core = await load('../../core/src/index.ts');
const { builds, TOKENS } = await load('../../core/test/starters.ts');

// Start clean, but keep the React app's node_modules so it installs only once.
for (const dir of ['svg', 'html', 'json', 'react', 'react-app/src']) {
  rmSync(join(out, dir), { recursive: true, force: true });
}
for (const dir of ['svg', 'html', 'json', 'react-app/src/icons']) {
  mkdirSync(join(out, dir), { recursive: true });
}

const iife = await bundleRuntime({ format: 'iife' });
const es = await bundleRuntime({ format: 'es' });
writeFileSync(join(out, 'icontween.iife.js'), iife);

const manifest = [];
for (const [key, build] of Object.entries(builds)) {
  const animation = build();
  const svg = core.exportSvg(animation, TOKENS, { size: 48 });
  const html = core.exportHtml(animation, TOKENS, { runtime: iife });
  const json = core.exportJson(animation, TOKENS);
  const react = core.exportReact(animation, TOKENS);
  writeFileSync(join(out, 'svg', svg.fileName), svg.text);
  writeFileSync(join(out, 'html', html.fileName), html.text);
  writeFileSync(join(out, 'json', json.fileName), json.text);
  writeFileSync(join(reactApp, 'src/icons', react.fileName), react.text);
  manifest.push({
    key,
    name: animation.name,
    trigger: animation.trigger.type,
    base: core.exportFileBase(animation),
    component: core.componentName(animation),
    svg: `svg/${svg.fileName}`,
    html: `html/${html.fileName}`,
    json: `json/${json.fileName}`,
  });
}
writeFileSync(join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

// --- The React app: Vite's react-ts template plus every exported component -------------

cpSync(join(here, 'react-app'), reactApp, { recursive: true });
writeFileSync(join(reactApp, 'src/icons/icontween.js'), es);
cpSync(join(here, '../types/icontween.d.ts'), join(reactApp, 'src/icons/icontween.d.ts'));
writeFileSync(join(reactApp, 'src/icons.ts'), iconsModule(manifest));

const run = (cmd, args) => execFileSync(cmd, args, { cwd: reactApp, stdio: 'inherit' });
if (!existsSync(join(reactApp, 'node_modules'))) {
  run('pnpm', ['install', '--ignore-workspace', '--prefer-offline', '--silent']);
}
// The template's own build: strict tsc, then vite build (into out/react).
run('pnpm', ['run', '--silent', 'build']);

cpSync(join(here, 'page'), out, { recursive: true });
console.log(`\nExport check: ${manifest.length} starters in ${out}`);

/** src/icons.ts: imports every component and lists it with its trigger. */
function iconsModule(items) {
  return [
    '// Generated by export-check/generate.js: every exported starter component.',
    "import type { ComponentType, RefAttributes, RefObject } from 'react';",
    ...items.map((i) => `import { ${i.component} } from './icons/${i.component}';`),
    '',
    '/** What every exported component accepts (a subset; each also has its own state ids). */',
    'export interface IconHandle {',
    '  play(): void;',
    '  reverse(): void;',
    '  toggle(): void;',
    '  stop(): void;',
    '}',
    'export interface IconProps {',
    '  size?: number | string;',
    "  trigger?: 'hover' | 'click' | 'toggle' | 'loop' | 'appear' | 'manual' | 'none';",
    '  listenOn?: RefObject<Element | null>;',
    "  reducedMotion?: 'auto' | 'reduce' | 'no-preference';",
    '}',
    'export type Icon = ComponentType<IconProps & RefAttributes<IconHandle>>;',
    '',
    'export const icons: { key: string; trigger: string; Component: Icon }[] = [',
    ...items.map(
      (i) => `  { key: '${i.key}', trigger: '${i.trigger}', Component: ${i.component} as Icon },`,
    ),
    '];',
    '',
  ].join('\n');
}
