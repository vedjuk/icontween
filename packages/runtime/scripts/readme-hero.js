/**
 * Builds docs/media/hero.svg: the twelve starters in a row of tiles, looping, for the README.
 *
 * Made with IconTween's own SVG + SMIL export (decision 017), so it plays as an <img> on
 * GitHub with no script. Each starter is switched to a looping trigger here, because only
 * loop and appear play inside an <img>: one-way moments (toggles, hover) go there and back,
 * the others repeat, each after a short rest, starting a little after the previous one.
 * When the OS asks for reduced motion, each icon follows its own reduced-motion setting.
 *
 * Usage: pnpm readme-hero (from the repo root). Reads examples/starters.icontween.json.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { JSDOM } from 'jsdom';
import { runnerImport } from 'vite';

const here = fileURLToPath(new URL('.', import.meta.url));
const root = join(here, '../../..');

globalThis.DOMParser = new JSDOM('').window.DOMParser;
const { module: core } = await runnerImport(join(root, 'packages/core/src/index.ts'), {
  configFile: false,
  logLevel: 'silent',
});

const read = core.parseProject(
  readFileSync(join(root, 'examples/starters.icontween.json'), 'utf8'),
);
if (!read.ok) throw new Error(`Couldn't read the starters: ${JSON.stringify(read)}`);
const project = read.value;

// Layout, in px. GitHub scales the image down to the column width (about 830 px).
const tile = 64;
const icon = 32;
const gap = 12;
const pad = 16;
const ink = '#1d1b26';
const count = project.animations.length;
const width = pad * 2 + count * tile + (count - 1) * gap;
const height = pad * 2 + tile;

const tiles = project.animations.map((animation, i) => {
  const returns = animation.sequence.steps.at(-1).to === animation.states[0].id;
  const looping = {
    ...animation,
    trigger: { type: 'loop' },
    sequence: {
      ...animation.sequence,
      repeat: returns ? 'loop' : 'ping-pong',
      restBetweenLoops: returns ? 1600 : 1200,
    },
  };
  const svg = core
    .exportSvg(looping, project.motionTokens, { size: icon })
    .text.replace(/currentColor/g, ink)
    // Start one after another, not all at once.
    .replace('begin="0s"', `begin="${(i * 0.25).toFixed(2)}s"`)
    .replace('<svg\n  xmlns="http://www.w3.org/2000/svg"', '<svg');
  const x = pad + i * (tile + gap);
  const inset = (tile - icon) / 2;
  return [
    `  <rect x="${x}" y="${pad}" width="${tile}" height="${tile}" rx="14" fill="#ffffff" stroke="#e4e1ec" />`,
    `  <g transform="translate(${x + inset} ${pad + inset})">`,
    indent(svg.trimEnd(), 4),
    `  </g>`,
  ].join('\n');
});

const out = [
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">`,
  `  <!-- The IconTween starters, looping. Generated by packages/runtime/scripts/readme-hero.js. -->`,
  `  <title>The twelve IconTween starters, animating</title>`,
  ...tiles,
  `</svg>`,
  '',
].join('\n');

const file = join(root, 'docs/media/hero.svg');
writeFileSync(file, out);
console.log(`Wrote ${file} (${(out.length / 1024).toFixed(1)} KB, ${count} icons)`);

function indent(text, spaces) {
  const pre = ' '.repeat(spaces);
  return text
    .split('\n')
    .map((line) => (line ? pre + line : line))
    .join('\n');
}
